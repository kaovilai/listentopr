/** Valid icon names (keys of SPRITE). */
export type IconName = keyof typeof SPRITE

/** id of the hidden sprite <svg> node injectSprite creates. */
export const SPRITE_ID = 'lpr-icon-sprite'

const SVG_NS = 'http://www.w3.org/2000/svg'

/** Presentation attributes carried by every <symbol> (Feather defaults). */
const SYMBOL_ATTRS: Readonly<Record<string, string>> = {
  fill: 'none',
  stroke: 'currentColor',
  'stroke-width': '2',
  'stroke-linecap': 'round',
  'stroke-linejoin': 'round',
}

function document_(): Document {
  const doc = (globalThis as { document?: Document }).document
  if (!doc || typeof doc.createElementNS !== 'function') {
    throw new Error('icons: no DOM document available for element creation')
  }
  return doc
}

function svgElement<K extends keyof SVGElementTagNameMap>(
  tag: K,
  doc: Document,
): SVGElementTagNameMap[K] {
  return doc.createElementNS(SVG_NS, tag) as SVGElementTagNameMap[K]
}

/**
 * Append the hidden icon sprite to target (once; a second call refreshes the
 * existing node in place instead of duplicating it). One
 * <symbol id="lpr-icon-<name>" viewBox="0 0 24 24"> per SPRITE entry.
 */
export function injectSprite(target: HTMLElement): void {
  const doc = document_()
  const existing = target.querySelector<SVGElement>(`#${SPRITE_ID}`)
  const sprite = existing ?? svgElement('svg', doc)
  sprite.id = SPRITE_ID
  sprite.setAttribute('style', 'display:none')
  sprite.setAttribute('aria-hidden', 'true')
  // Refresh: drop stale symbols so a rebuilt SPRITE never leaves orphans.
  while (sprite.firstChild) sprite.removeChild(sprite.firstChild)
  for (const [name, markup] of Object.entries(SPRITE)) {
    const symbol = svgElement('symbol', doc)
    symbol.id = `lpr-icon-${name}`
    symbol.setAttribute('viewBox', '0 0 24 24')
    for (const [attr, value] of Object.entries(SYMBOL_ATTRS)) {
      symbol.setAttribute(attr, value)
    }
    symbol.innerHTML = markup
    sprite.appendChild(symbol)
  }
  if (!existing) target.appendChild(sprite)
}

/**
 * A standalone <svg> referencing a sprite symbol via <use>. Decorative by
 * default: theme-agnostic (currentColor) and hidden from a11y tree.
 */
export function icon(name: IconName): SVGSVGElement {
  if (typeof name !== 'string' || !(name in SPRITE)) {
    throw new Error(`icons: unknown icon name: ${String(name)}`)
  }
  const doc = document_()
  const svg = svgElement('svg', doc)
  svg.setAttribute('class', 'icon')
  svg.setAttribute('viewBox', '0 0 24 24')
  svg.setAttribute('aria-hidden', 'true')
  svg.setAttribute('focusable', 'false')
  const use = svgElement('use', doc)
  use.setAttribute('href', `#lpr-icon-${name}`)
  svg.appendChild(use)
  return svg
}
